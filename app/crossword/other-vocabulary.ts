export type VocabularyPart = "名词" | "形容词" | "副词" | "其他";

export type OtherVocabularySeed = {
  word: string;
  meaning: string;
  partOfSpeech: VocabularyPart;
};

function parseSeeds(source: string, partOfSpeech: VocabularyPart) {
  return source
    .trim()
    .split("\n")
    .map((line) => {
      const [word, meaning] = line.split("|");
      return { word, meaning, partOfSpeech };
    });
}

